type OsId = "ubuntu" | "macos" | "amazon" | "rhel";
type ViewId = "install" | "configs" | "summary";
type InstallStepKey = "packages" | "shell" | "dotfiles" | "tools";
type DockerStrategyId = "official" | "distro" | "podman" | "none";
type NodeStrategyId = "mise" | "nvm" | "none";
type ConfigKey = "zshrc" | "vimrc" | "tmux" | "htop";

type OsTarget = {
  id: OsId;
  label: string;
  packageManager: string;
  commandTarget: string;
  implemented: boolean;
  note: string;
};

type PackageGroup = {
  id: string;
  title: string;
  description: string;
  defaultEnabled: boolean;
};

type CatalogPackage = {
  id: string;
  group: string;
  label: string;
  defaultSelected: boolean;
  packages: Record<OsId, string[]>;
  note?: string;
};

type Strategy = {
  id: string;
  label: string;
  description: string;
  defaults?: OsId[];
};

type Catalog = {
  osTargets: OsTarget[];
  groups: PackageGroup[];
  packages: CatalogPackage[];
  strategies: {
    docker: Strategy[];
    node: Strategy[];
  };
};

const catalog = catalogData as Catalog;

